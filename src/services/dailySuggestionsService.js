import { fetchAvailableGeminiModels } from "./geminiApi.js";
import { getCityTodayDateStr, KEYS } from "./storage.js";

/**
 * Returns the cached suggestions object from localStorage.
 */
export function getDailySuggestionsCache() {
	try {
		const raw = localStorage.getItem(
			KEYS.DAILY_SUGGESTIONS || "prayer_tracker_daily_suggestions",
		);
		if (!raw) return null;
		return JSON.parse(raw);
	} catch {
		return null;
	}
}

/**
 * Saves suggestions to localStorage and notifies listeners.
 */
export function saveDailySuggestionsCache(
	dateStr,
	lang,
	suggestions,
	generatedByAi = true,
) {
	try {
		if (!Array.isArray(suggestions) || suggestions.length === 0) return null;
		const data = {
			date: dateStr,
			lang: lang || "ar",
			suggestions: suggestions.slice(0, 4),
			generatedByAi: Boolean(generatedByAi),
			timestamp: Date.now(),
		};
		localStorage.setItem(
			KEYS.DAILY_SUGGESTIONS || "prayer_tracker_daily_suggestions",
			JSON.stringify(data),
		);
		window.dispatchEvent(
			new CustomEvent("prayer_tracker_suggestions_updated", { detail: data }),
		);
		return data;
	} catch (err) {
		logError("saveDailySuggestionsCache", err);
		return null;
	}
}

/**
 * Gets the current daily suggestions. If generated by AI and cached for today, returns them.
 * Otherwise returns empty array (zero hardcoded fallback questions).
 */
export function getDailySuggestions(lang = "ar") {
	const todayStr = getCityTodayDateStr();
	const cached = getDailySuggestionsCache();

	if (
		cached &&
		cached.date === todayStr &&
		cached.lang === lang &&
		cached.generatedByAi &&
		Array.isArray(cached.suggestions) &&
		cached.suggestions.length >= 1
	) {
		return cached.suggestions;
	}

	return [];
}

/**
 * Robust extractor that handles JSON, markdown code blocks, raw arrays, or plain-text question lines.
 */
export function extractSuggestionsFromText(rawText) {
	if (!rawText || !rawText.trim()) return [];

	// 1. Clean markdown code fences if present
	const clean = rawText
		.trim()
		.replace(/^```(?:json)?\s*/i, "")
		.replace(/\s*```$/i, "")
		.trim();
	try {
		const parsed = JSON.parse(clean);
		if (Array.isArray(parsed) && parsed.length > 0) return parsed;
		if (Array.isArray(parsed?.suggestions) && parsed.suggestions.length > 0)
			return parsed.suggestions;
		if (Array.isArray(parsed?.questions) && parsed.questions.length > 0)
			return parsed.questions;
		if (Array.isArray(parsed?.items) && parsed.items.length > 0)
			return parsed.items;
	} catch {}

	// 2. Regex matching for JSON object
	const matchObj = rawText.match(/\{[\s\S]*?\}/);
	if (matchObj) {
		try {
			const parsed = JSON.parse(matchObj[0]);
			if (Array.isArray(parsed?.suggestions) && parsed.suggestions.length > 0)
				return parsed.suggestions;
			if (Array.isArray(parsed?.questions) && parsed.questions.length > 0)
				return parsed.questions;
		} catch {}
	}

	// 3. Regex matching for JSON array
	const matchArr = rawText.match(/\[[\s\S]*?\]/);
	if (matchArr) {
		try {
			const parsed = JSON.parse(matchArr[0]);
			if (Array.isArray(parsed) && parsed.length > 0) return parsed;
		} catch {}
	}

	// 4. Line-by-line fallback extracting interrogative Arabic/English sentences
	const lines = rawText
		.split(/[\r\n]+/)
		.map((l) => l.replace(/^[\d.\-*•\s"«“`]+|["»”`\s]+$/g, "").trim())
		.filter(
			(l) =>
				l.length >= 6 && l.length <= 80 && (l.includes("؟") || l.includes("?")),
		);

	return lines.slice(0, 4);
}

// In-flight guard to prevent parallel duplicate API requests on the same day
let isFetchingDailySuggestions = false;

/**
 * System-initiated daily trigger: Sends a single request to the model once per day
 * to generate fresh, contextual suggested prompts based on the user's live habit data.
 */
export async function ensureDailySuggestions(
	geminiApiKey,
	lang = "ar",
	signal = null,
) {
	if (typeof navigator !== "undefined" && !navigator.onLine)
		return getDailySuggestions(lang);
	if (isFetchingDailySuggestions) return getDailySuggestions(lang);
	if (!geminiApiKey || !geminiApiKey.trim()) return getDailySuggestions(lang);

	const todayStr = getCityTodayDateStr();
	const cached = getDailySuggestionsCache();

	// Already generated by AI for today and matching language -> Skip API call completely
	if (
		cached &&
		cached.date === todayStr &&
		cached.lang === lang &&
		cached.generatedByAi &&
		Array.isArray(cached.suggestions) &&
		cached.suggestions.length >= 1
	) {
		return cached.suggestions;
	}

	isFetchingDailySuggestions = true;

	try {
		const isEn = lang === "en";
		const contextSummary = await formatAppContextForPrompt();
		const safeSummary =
			typeof contextSummary === "string" ? contextSummary : "";

		const systemPrompt = isEn
			? `You are the suggestion generator for Sheikh Muneer, an Islamic scholar and habit tracker assistant.
Based on the application context, generate exactly 4 concise, diverse questions that the USER can ASK Sheikh Muneer (written strictly from the user's perspective inquiring about prayer, fiqh, daily habits, or Quran, each 4 to 9 words).
CRITICAL RULE: The questions must NOT be directed at the user (do NOT ask "Did you pray?" or "How do you feel?"). Every question must be a prompt asked BY the user TO the Sheikh (e.g. "How can I maintain Fajr prayer on time?", "What are the confirmed daily Sunnah prayers?", "What is the ruling on doubt in prayer?").
Return strictly a valid JSON object matching this schema:
{"suggestions": ["Question asked by user?", "Question asked by user?", "Question asked by user?", "Question asked by user?"]}
Do not output markdown code blocks or any explanation, only the pure JSON string.`
			: `أنت محرك إنشاء الاقتراحات اليومية للشيخ منير في تطبيق تتبع العادات والصلوات.
بناءً على سياق التطبيق وبيانات المستخدم المرفقة، قم بإنشاء 4 أسئلة يطرحها المستخدم على الشيخ منير (أسئلة بصيغة المتكلم يسأل بها المستخدم الشيخ منير، وليست أسئلة موجهة من الشيخ للمستخدم).
يجب أن تكون الأسئلة متنوعة، ملهمة، وموجزة (بين 4 إلى 9 كلمات لكل سؤال)، مثل: "كيف أحافظ على صلاة الفجر في وقتها؟"، "ما فضل صلاة الضحى والسنن الرواتب؟"، "كيف أنظم وردي القرآني اليومي؟"، "ما حكم الشك والسهو في الصلاة؟".
تنبيه صارم: يُمنع منعاً باتاً صياغة أسئلة موجهة للمستخدم (مثل "هل صليت اليوم؟" أو "كيف تشعر؟")، بل كل سؤال هو سؤال يبدأ به المستخدم حواره مع الشيخ ليستفتيه أو يستنصحه.
أرجع حصرياً كائن JSON بالهيكل التالي فقط:
{"suggestions": ["سؤال يطرحه المستخدم للشيخ؟", "سؤال يطرحه المستخدم للشيخ؟", "سؤال يطرحه المستخدم للشيخ؟", "سؤال يطرحه المستخدم للشيخ؟"]}
ممنوع كتابة أي شروحات أو كتل كود markdown خارج كائن الـ JSON.`;

		const userPrompt = isEn
			? `Today's Date: ${todayStr}\n\nApp Context:\n${safeSummary.slice(0, 1500)}\n\nGenerate 4 questions that the user can ask Sheikh Muneer today.`
			: `تاريخ اليوم: ${todayStr}\n\nسياق التطبيق:\n${safeSummary.slice(0, 1500)}\n\nأنشئ 4 أسئلة يطرحها المستخدم على الشيخ منير لليوم.`;

		const dynamicModels = await fetchAvailableGeminiModels(geminiApiKey.trim());

		for (const model of dynamicModels) {
			try {
				const res = await fetch(
					`https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${geminiApiKey.trim()}`,
					{
						method: "POST",
						headers: { "Content-Type": "application/json" },
						signal,
						body: JSON.stringify({
							contents: [
								{
									role: "user",
									parts: [{ text: `${systemPrompt}\n\n${userPrompt}` }],
								},
							],
							generationConfig: {
								temperature: 0.7,
								maxOutputTokens: 300,
							},
						}),
					},
				);

				if (res.ok) {
					const data = await res.json();
					const rawText =
						data?.candidates?.[0]?.content?.parts?.[0]?.text || "";
					const rawSuggestions = extractSuggestionsFromText(rawText);

					if (Array.isArray(rawSuggestions) && rawSuggestions.length >= 1) {
						const cleanedSuggestions = rawSuggestions
							.map((s) =>
								String(s)
									.replace(/^[\d.\-*\s]+/, "")
									.trim(),
							)
							.filter((s) => s.length > 3)
							.slice(0, 4);

						if (cleanedSuggestions.length >= 1) {
							saveDailySuggestionsCache(
								todayStr,
								lang,
								cleanedSuggestions,
								true,
							);
							return cleanedSuggestions;
						}
					}
				}
			} catch (e) {
				console.warn(
					`Model ${model} daily suggestions generation failed, trying next:`,
					e,
				);
			}
		}
	} catch (err) {
		if (err?.name !== "AbortError") {
			logError("ensureDailySuggestions", err);
		}
	} finally {
		isFetchingDailySuggestions = false;
	}

	return getDailySuggestions(lang);
}
